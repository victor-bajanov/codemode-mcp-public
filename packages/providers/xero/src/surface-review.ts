  "Unreachable as deployed: `/Journals` is the general-ledger journal-lines feed and needs " +
  "the `accounting.journals.read` scope, which this server does not request (Xero rejects it " +
  "as invalid_scope for this client_id), so the call fails upstream with 403. This does NOT " +
  "affect ManualJournals — `getManualJournals` is available and is the right endpoint for " +
  "manual journal entries. For posted activity use the reports or bank-transaction endpoints.";

/** Payroll WRITE scopes are not requested — only the `.read` halves are. These
 *  four are elicit-gated, so without this note the client is told to seek
 *  approval for a call the token could never make. */
