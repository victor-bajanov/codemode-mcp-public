/** makeDraftStatusInspector — same policy for invoices and credit notes, with
 *  the resource's own array wrapper, id field and article substituted in.
 *  `article` is explicit because "a invoice" is what interpolation produces. */
const draftStatusNote = (arrayKey: string, idField: string, article: string, label: string): string =>
  `Each item in \`${arrayKey}\` (or the flat by-id body) is status-gated: \`Status\` must be ` +
  `"DRAFT" or "SUBMITTED"; ANY other value is denied, including the AUTHORISED/VOIDED/DELETED ` +
  `transitions that are Xero's only way to post, void or delete ${article} ${label} — so none ` +
  `of those is possible here. \`Status\` may be omitted only if the item carries ` +
  `\`${idField}\` (read from the body, not the path); otherwise the create is denied as ` +
  `implicitly AUTHORISED. \`SentToContact: true\` is denied — it emails the ${label} to the ` +
  `contact. An empty payload is denied.`;

// Not inspector conditions: these reads are gated on scopes this deployment
// does not hold, so they fail before any policy applies. NB `/Journals` is the
// general-ledger journal-lines feed, NOT ManualJournals — the latter's scope
// (accounting.manualjournals.read) IS granted and getManualJournals works.
//
// The rule applied here is NOT "every scope the op accepts is ungranted" — that
// flags 83 surface entries, essentially all false positives, because the
// bundled spec still declares the deprecated coarse families
// (accounting.transactions.read, accounting.settings.read, …) that index.ts
// deliberately replaced with granular scopes. A full audit would need a
// coarse→granular mapping table that does not exist in this repo, and guessing
// at it is worse than not auditing.
//
// The rule that IS applied: every scope the operation accepts is ungranted AND
// none of them is a deprecated coarse family with a granted granular
// replacement. That is mechanically checkable (see client-notes.test.ts, which
// recomputes it) and yields the five entries below.
