/** makeDraftStatusInspector + makeStoredStatusHook — same policy for invoices
 *  and credit notes, with the resource's own array wrapper, id field, number
 *  field and article substituted in. `article` is explicit because "a invoice"
 *  is what interpolation produces. (Security review F2-4: Status is required on
 *  every item, and the stored document is read before an update.) */
const draftStatusNote = (
  arrayKey: string,
  idField: string,
  numberField: string,
  article: string,
  label: string,
): string =>
  `Each item in \`${arrayKey}\` (or the flat by-id body) is status-gated: \`Status\` is required and ` +
  `must be "DRAFT" or "SUBMITTED"; omitting it, or ANY other value (including the ` +
  `AUTHORISED/VOIDED/DELETED transitions that are Xero's only way to post, void or delete ` +
  `${article} ${label}), is denied. An item carrying \`${idField}\` is read from Xero before ` +
  `sending and is denied unless the stored ${label} is itself DRAFT or SUBMITTED; an item with no ` +
  `\`${idField}\` but a \`${numberField}\` is read by that number first and is denied if ` +
  `${article} ${label} with that number exists and is not a draft (\`${numberField}\` must be a ` +
  `string with no leading or trailing spaces; a number containing "/" cannot be read and is ` +
  `refused). At most 4 items carrying \`${idField}\` or \`${numberField}\` per request (each is ` +
  `read first, numbered creates included). On the by-id endpoint the body takes exactly ` +
  `one item and a body \`${idField}\` must equal the path id. Nothing may sit beside ` +
  `\`${arrayKey}\`, and \`Status\` must be a string. The inline \`Contact\` may not carry bank, ` +
  `batch-payment, email, status, tax-number or contact-person details. \`SentToContact: true\` ` +
  `is denied — it emails the ${label} to the contact. An empty payload is denied.`;

